  function translate(value, target) {
    var source=String(value), lang=target||language;
    if(lang==='en') return source;
    var compact=source.replace(/\s+/g,' ').trim(), result=Object.prototype.hasOwnProperty.call(ZH,compact)?ZH[compact]:undefined;
    if(result===undefined){
      // User content and paths are never translated by substring replacement.
      if(/^(?:\/?(?:data|mnt)\/|https?:\/\/|[A-Z]:[\\/])/.test(compact))return source;
      for(var i=0;i<patterns.length;i++){var match=compact.match(patterns[i][0]);if(match){result=patterns[i][1](match);break;}}
      if(result===undefined&&/\.(mp4|mp3|png|jpe?g|apng|gif)$/i.test(compact))return source;
      if(result===undefined&&compact.indexOf(' · ')>=0)result=compact.split(' · ').map(function(s){return translate(s,'zh-CN')}).join(' · ');
      if(result===undefined&&compact.indexOf(': ')>=0){var at=compact.indexOf(': '),prefix=ZH[compact.slice(0,at)];if(prefix!==undefined)result=prefix+'：'+translate(compact.slice(at+2),'zh-CN');}
    }
    return result===undefined?source:source.replace(/\S[\s\S]*\S|\S/,function(){return result;});
  }
  function ignored(element){if(!element||element.closest('script,style,code,textarea,#title,[data-no-i18n]'))return true;return !!element.closest('.name,.nt,.vname,.lname,.vlab,.nm')&&!element.closest('.lhead,.now,.tag,.res,.snd');}
  function apply(){
    scheduled=false;if(typeof document==='undefined'||!document.body)return;
    document.documentElement.lang=language;
    var walk=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT,null,false),node;
    while((node=walk.nextNode())){
      if(ignored(node.parentElement)||!node.nodeValue.trim())continue;
      var previous=texts.get(node),current=node.nodeValue;
      var original=previous&&previous.last===current?previous.source:current;
      var translated=translate(original);texts.set(node,{source:original,last:translated});
      if(current!==translated)node.nodeValue=translated;
    }
    var elements=document.querySelectorAll('[title],[placeholder],[aria-label]');
    for(var i=0;i<elements.length;i++){
      var element=elements[i];if(ignored(element))continue;
      var record=attrs.get(element)||{};
      ['title','placeholder','aria-label'].forEach(function(key){
        if(!element.hasAttribute(key))return;
        var current=element.getAttribute(key),old=record[key],original=old&&old.last===current?old.source:current;
        var translated=translate(original);record[key]={source:original,last:translated};if(current!==translated)element.setAttribute(key,translated);
      });attrs.set(element,record);
    }
  }
